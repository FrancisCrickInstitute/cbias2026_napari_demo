import pytest
from magicgui import magicgui

from cbias2026_plugin import _widget
from cbias2026_plugin._widget import (
    CLICK_MESSAGES,
    ExampleContainer,
    ExampleQWidget,
    example_factory,
    example_function,
)


@pytest.fixture
def shown_messages(monkeypatch):
    messages = []
    monkeypatch.setattr(_widget, 'show_info', messages.append)
    return messages


def test_autogenerated_function_relabels_button_on_click(shown_messages):
    # napari wraps `autogenerate: true` functions with magicgui
    widget = magicgui(example_function)
    assert widget._call_button.text == 'Run'

    widget()

    assert widget._call_button.text == 'Click me (function)'
    assert len(shown_messages) == 1
    assert shown_messages[0] in CLICK_MESSAGES


def test_magic_factory_button(shown_messages):
    widget = example_factory()
    assert widget._call_button.text == 'Click me (factory)'

    widget._call_button.native.click()

    assert shown_messages[0] in CLICK_MESSAGES


def test_container_button(make_napari_viewer, shown_messages):
    widget = ExampleContainer(make_napari_viewer())

    widget.btn.native.click()

    assert shown_messages[0] in CLICK_MESSAGES


def test_qwidget_button(make_napari_viewer, shown_messages):
    widget = ExampleQWidget(make_napari_viewer())

    widget.btn.click()
    widget.btn.click()

    assert len(shown_messages) == 2
    assert all(m in CLICK_MESSAGES for m in shown_messages)
