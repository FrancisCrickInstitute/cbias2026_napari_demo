"""
Four ways of making the same button widget, one per approach napari supports:

- a plain function flagged with `autogenerate: true` in the manifest, which
    napari wraps with magicgui for us.
- a `magic_factory` decorated function, which lets us customise the
    generated widget (here, the call button text).
- a `magicgui.widgets.Container` subclass, for building a widget out of
    magicgui widgets and wiring up our own callbacks.
- a `QWidget` subclass, for full control via Qt.

References:
- Widget specification: https://napari.org/stable/plugins/building_a_plugin/guides.html#widgets
- magicgui docs: https://pyapp-kit.github.io/magicgui/
"""

import random
from typing import TYPE_CHECKING

from magicgui import magic_factory
from magicgui.widgets import Container, create_widget
from napari.utils.notifications import show_info
from qtpy.QtWidgets import QPushButton, QVBoxLayout, QWidget

if TYPE_CHECKING:
    import napari

CLICK_MESSAGES = (
    'Ow!',
    'Stop it!',
    'That hurts!',
    'Please stop!',
    "I'm telling!",
    'I have been clicked',
    'Ouch!',
    "I have altered the code, pray I don't alter it further",
    'Are you having fun?',
    'This was generated by Copilot',
    "This isn't cookie clicker",
)


def button_click_callback():
    """Shared by every widget below, so only the widget plumbing differs."""
    show_info(random.choice(CLICK_MESSAGES))


def example_function():
    # While a magicgui-wrapped function runs, magicgui temporarily rebinds its
    # name to the FunctionGui, so this reaches into a private attribute to
    # relabel the button. It only takes effect after the first click: with
    # `autogenerate: true` there is no supported way to customise the widget.
    example_function._call_button.text = 'Click me (function)'
    button_click_callback()


@magic_factory(call_button='Click me (factory)')
def example_factory():
    button_click_callback()


class ExampleContainer(Container):
    def __init__(self, viewer: 'napari.viewer.Viewer'):
        super().__init__()
        self._viewer = viewer
        self.btn = create_widget(
            label='Click me (Container)', widget_type='PushButton'
        )
        self.btn.clicked.connect(button_click_callback)
        self.extend([self.btn])


class ExampleQWidget(QWidget):
    # napari passes the viewer to any parameter annotated with
    # 'napari.viewer.Viewer'
    def __init__(self, viewer: 'napari.viewer.Viewer'):
        super().__init__()
        self.viewer = viewer

        self.btn = QPushButton('Click me (QWidget)')
        self.btn.clicked.connect(button_click_callback)

        self.setLayout(QVBoxLayout())
        self.layout().addWidget(self.btn)
